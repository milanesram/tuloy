import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {publishCode} from '../scripts/publish-tuloy.mjs';

test('code publication starts fresh, excludes committed private data, blocks new files, and preserves private runtime',t=>{
  const temp=fs.mkdtempSync(path.join(os.tmpdir(),'tuloy-publish-test-'));t.after(()=>fs.rmSync(temp,{recursive:true,force:true}));
  const source=path.join(temp,'working'),target=path.join(temp,'publishing');fs.mkdirSync(source);fs.mkdirSync(target);
  const git=(cwd,...args)=>execFileSync('git',args,{cwd,encoding:'utf8',stdio:'pipe'}).trim();
  const put=(name,text)=>{const p=path.join(source,name);fs.mkdirSync(path.dirname(p),{recursive:true});fs.writeFileSync(p,text);};
  git(source,'init','-q','-b','main');git(target,'init','-q','-b','main');git(target,'remote','add','origin','https://github.com/milanesram/tuloy.git');
  put('README.md','Public code');put('.gitignore','data/\ncv.md\nportals.yml\nREADME.md\n');
  put('cv.md','PRIVATE CV');put('portals.yml','PRIVATE PARAMETERS');put('data/results.md','PRIVATE RESULTS');
  for(const name of ['config/profile.example.yml','config/plugins.example.yml','config/cv-facts.example.json','config/career-strategies.example.json']) put(name,'{}');
  put('docs/tuloy/ci-template.yml','name: Test');
  const approved=['README.md','.gitignore','publication-files.json','config/profile.example.yml','config/plugins.example.yml','config/cv-facts.example.json','config/career-strategies.example.json','config/portals.example.yml','docs/tuloy/ci-template.yml','.github/workflows/tuloy-ci.yml'];
  put('publication-files.json',JSON.stringify(approved));
  git(source,'add','-f','.');git(source,'-c','user.name=Fixture','-c','user.email=fixture@example.invalid','commit','-qm','Private original history');
  publishCode(source,target,'Initial public source');
  assert.equal(git(target,'rev-list','--count','HEAD'),'1');
  assert.match(git(target,'log','-1','--format=%ae'),/noreply.github.com/);
  for(const name of ['cv.md','portals.yml','data/results.md']) assert.equal(fs.existsSync(path.join(target,name)),false);
  assert.equal(fs.readFileSync(path.join(source,'cv.md'),'utf8'),'PRIVATE CV');
  fs.mkdirSync(path.join(target,'data'));fs.writeFileSync(path.join(target,'data/ignored.md'),'PRIVATE LOCAL');
  put('README.md','Updated public code');publishCode(source,target,'Update');
  assert.equal(git(target,'show','HEAD:README.md'),'Updated public code');
  assert.equal(git(target,'ls-files','data'),'');
  const head=git(target,'rev-parse','HEAD');
  put('private-notes.txt','DO NOT PUBLISH');assert.throws(()=>publishCode(source,target,'Blocked'),/privacy review/);
  assert.equal(git(target,'rev-parse','HEAD'),head);assert.equal(git(target,'status','--porcelain'),'');
  fs.unlinkSync(path.join(source,'private-notes.txt'));
  put('README.md','-----BEGIN '+'PRIVATE KEY-----');assert.throws(()=>publishCode(source,target,'Blocked secret'),/preflight/);
  assert.equal(git(target,'rev-parse','HEAD'),head);
  put('README.md','Updated public code');
  git(target,'remote','set-url','origin','https://github.com/other/other.git');
  assert.throws(()=>publishCode(source,target,'Wrong destination'),/destination/);
  assert.throws(()=>publishCode(source,source,'Wrong checkout'),/separate/);
});
